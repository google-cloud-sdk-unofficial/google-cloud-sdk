"""Implements command to validate migrated data against its source."""

from googlecloudsdk.calliope import base
from googlecloudsdk.command_lib.bq.migration import validation_client
from googlecloudsdk.command_lib.bq.migration import validation_flags


@base.RegionalEndpointsSupported
@base.DefaultUniverseOnly
@base.ReleaseTracks(base.ReleaseTrack.ALPHA)
@base.Hidden
class Run(base.Command):
  """Validate data migrated to BigQuery against its source."""

  detailed_help = {
      'DESCRIPTION': (
          """\
          Validate the data of the tables described by the configuration
          files generated by `{parent_command} configure`. For each table, the
          BigQuery Migration Validation Client connects to the source data
          warehouse, extracts the schema, aggregates, and row samples of the
          table, stages them in the Cloud Storage location given by the
          configuration (or `--gcs-path`), and creates a BigQuery Migration
          Service validation workflow in `--location` that compares them with
          the migrated BigQuery table. The client prints the workflow name,
          the staged Cloud Storage path, and the BigQuery results location of
          each table, and exits when all workflows have been created.

          The client runs on this machine and requires Java 11 or later on
          your `PATH`; the `bqms` component of the gcloud CLI, which contains
          the client, is installed on first use if it is missing. The client
          authenticates to Google Cloud with Application Default Credentials
          (for example, from `gcloud auth application-default login`), which
          must be allowed to write to the Cloud Storage staging location, to
          create BigQuery Migration Service workflows in the project of the
          migrated tables, and to run BigQuery jobs in that project that read
          the migrated tables and write the validation results. The
          credentials of the source data warehouse are read from the
          `connections.yaml` file of the configuration. To pass additional
          options to the Java virtual machine, set the `JAVA_OPTS` environment
          variable, for example `export JAVA_OPTS=-Xmx8G` (Linux and macOS) or
          `set JAVA_OPTS=-Xmx8G` (Windows Command Prompt).

          Arguments after `--` are forwarded to the validation client
          unchanged.
          """
      ),
      'EXAMPLES': (
          """\
          To validate the tables configured under `./validation_config` with
          validation workflows in location `us`, run:

            $ {command} validation_config --location=us

          To validate only the tables `sales.orders` and `sales.customers`,
          staging the source samples under `gs://my-bucket/validation/`, run:

            $ {command} validation_config --location=us \\
                --tables=sales.orders,sales.customers \\
                --gcs-path=gs://my-bucket/validation/

          To only compare the schemas and aggregates of the configured tables,
          run:

            $ {command} validation_config --location=us \\
                --validation-types=schema,aggregate
          """
      ),
  }

  @staticmethod
  def Args(parser):
    validation_flags.AddRunFlags(parser)

  def Run(self, args):
    validation_client.Run(
        validation_client.VALIDATE_SUBCOMMAND,
        validation_flags.GetRunClientArgs(args),
        env_overrides=validation_flags.GetRunClientEnv(args),
    )
