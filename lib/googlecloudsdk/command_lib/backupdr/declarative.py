"""Functions for Backupdr gcloud declarative commands."""

import collections
import json
from typing import Any, Optional

from apitools.base.py import encoding
from apitools.base.py import extra_types
from googlecloudsdk.core.resource import resource_printer_base


class ApiJsonOrderedDict(collections.OrderedDict):
  """OrderedDict preserving the raw JSON response order from the API."""

  def __str__(self) -> str:
    return (
        json.dumps(
            self,
            indent=resource_printer_base.STRUCTURED_INDENTATION,
            sort_keys=False,
            separators=(',', ': '),
            ensure_ascii=False,
        )
        + '\n'
    )


def _OrderByMessageTags(msg: Any, record: Any) -> Any:
  """Recursively orders dict keys according to msg._Message__tags order.

  Args:
    msg: The decoded apitools Message or JsonValue instance containing field
      metadata and tag ordering, or a nested list/primitive.
    record: The dictionary or list generated by encoding.MessageToDict(response)
      whose keys should be recursively reordered.

  Returns:
    An ApiJsonOrderedDict, list, or primitive matching record structure with
    keys ordered according to the message definition.
  """
  if isinstance(msg, extra_types.JsonValue):
    if msg.object_value is not None:
      msg = msg.object_value
    elif msg.array_value is not None:
      msg = msg.array_value.entries
    else:
      msg = None
  if isinstance(record, list):
    items = (
        msg
        if isinstance(msg, list) and len(msg) == len(record)
        else [None] * len(record)
    )
    return [
        _OrderByMessageTags(item_msg, item_record)
        for item_msg, item_record in zip(items, record)
    ]
  if not isinstance(record, dict):
    return record
  # apitools / protorpclite Message classes record field tag numbers in
  # _Message__tags in the order they were defined in the message specification.
  # apitools does not expose a public API for message field declaration order,
  # so we inspect _Message__tags to preserve API JSON field ordering.
  tags = getattr(msg, '_Message__tags', {})
  properties = (
      msg.properties
      if isinstance(msg, extra_types.JsonObject)
      else getattr(msg, 'additionalProperties', None) or []
  )
  props = {prop.key: prop.value for prop in properties}
  ordered_keys = [msg.field_by_number(tag).name for tag in tags] + list(props)
  all_keys = ordered_keys + [key for key in record if key not in ordered_keys]
  return ApiJsonOrderedDict(
      (
          key,
          _OrderByMessageTags(
              props.get(key, getattr(msg, key, None)), record[key]
          ),
      )
      for key in all_keys
      if key in record
  )


def PreserveApiJsonOrderResponseHook(
    response: Optional[Any], unused_args: Any
) -> Optional[Any]:
  """Generic modify_response_hook that preserves API JSON field order.

  Args:
    response: The apitools response message returned by the API call, or None.
    unused_args: The parsed command-line args namespace; unused.

  Returns:
    An ApiJsonOrderedDict with keys ordered matching the API message definition,
    or None if response is None.
  """
  del unused_args  # Unused.
  if response is None:
    return None
  return _OrderByMessageTags(response, encoding.MessageToDict(response))


def SetBasicViewByDefaultRequestHook(ref, args, request):
  """Add basic view as a default field to list request.

  Args:
    ref: A parsed resource reference; unused.
    args: The parsed args namespace from CLI; unused.
    request: List request for the API call.

  Returns:
    Modified request that includes the view field set to basic view.
  """
  del ref, args  # Unused.
  # Access the ViewValueValuesEnum from the request instance's own class.
  # This ensures compatibility across v1, v1beta, and v1alpha.
  if hasattr(request, 'ViewValueValuesEnum'):
    request.view = request.ViewValueValuesEnum.BACKUP_VIEW_BASIC

  return request
